const dictionaries: { [lang in AppLanguage]: Dictionary } = { en, de, ru, lt };

/** Locale for dates in status texts */
export const LOCALES: { [lang in AppLanguage]: string } = { en: 'en-US', de: 'de-DE', ru: 'ru-RU', lt: 'lt-LT' };

export function translate(key: string, lang: AppLanguage, params?: { [k: string]: string | number }): string {
    let text = dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? key;
    if (params) {
        for (const [k, v] of Object.entries(params)) {
            text = text.split(`{${k}}`).join(String(v));
        }
    }
    return text;
}

export function normalizeLanguage(language: string | undefined): AppLanguage {
    const base = (language ?? 'en').toLowerCase().split(/[-_]/)[0];
    return base === 'de' || base === 'ru' || base === 'lt' ? base : 'en';
}

/** Every language has every key of the English dictionary (checked by the tests) */
export function missingKeys(): Array<string> {
    const keys = Object.keys(en);
    const missing: Array<string> = [];
    for (const lang of Object.keys(dictionaries) as Array<AppLanguage>) {
        for (const key of keys) {
            if (!(key in dictionaries[lang])) {
                missing.push(`${lang}.${key}`);
            }
        }
    }
    return missing;
}
